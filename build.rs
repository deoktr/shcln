use std::collections::HashMap;
use std::env;
use std::fs;
use std::path::PathBuf;

use regex_syntax::hir::{Hir, HirKind};
use regex_syntax::Parser;

fn main() {
    println!("cargo:rerun-if-changed=src/patterns.tsv");
    println!("cargo:rerun-if-changed=build.rs");

    let source = fs::read_to_string("src/patterns.tsv").expect("read src/patterns.tsv");

    let mut patterns: Vec<(String, String, String, String)> = Vec::new();
    for (line_no, line) in source.lines().enumerate() {
        let line = line.strip_suffix('\r').unwrap_or(line);
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut fields = line.splitn(4, '\t');
        let provider = fields.next().unwrap_or_default().trim();
        let name = fields.next().unwrap_or_default().trim();
        let id = fields.next().unwrap_or_default().trim();
        let regex = match fields.next() {
            Some(regex) => regex,
            None => panic!(
                "src/patterns.tsv:{}: expected provider<TAB>name<TAB>id<TAB>regex",
                line_no + 1
            ),
        };
        if id.is_empty() {
            panic!("src/patterns.tsv:{}: pattern id is empty", line_no + 1);
        }
        patterns.push((
            provider.to_string(),
            name.to_string(),
            id.to_string(),
            regex.to_string(),
        ));
    }

    // Keep in sync with MAX_PATTERNS in src/prefilter.rs. The runtime
    // prefilter uses a fixed-size stack bitset, so catch growth here instead
    // of panicking at startup.
    const MAX_PATTERNS: usize = 1024;
    if patterns.len() > MAX_PATTERNS {
        panic!(
            "src/patterns.tsv contains {} patterns, but the prefilter supports at most {}",
            patterns.len(),
            MAX_PATTERNS
        );
    }

    let mut keywords: Vec<String> = Vec::new();
    let mut keyword_patterns: Vec<Vec<usize>> = Vec::new();
    let mut keyword_index: HashMap<String, usize> = HashMap::new();
    let mut always: Vec<usize> = Vec::new();

    for (idx, (_, _, _, regex)) in patterns.iter().enumerate() {
        let literals = required_literals(regex, idx);
        if literals.is_empty() {
            always.push(idx);
            continue;
        }
        for literal in literals {
            let pos = match keyword_index.get(&literal) {
                Some(&pos) => pos,
                None => {
                    let pos = keywords.len();
                    keywords.push(literal.clone());
                    keyword_patterns.push(Vec::new());
                    keyword_index.insert(literal, pos);
                    pos
                }
            };
            keyword_patterns[pos].push(idx);
        }
    }

    let mut offsets: Vec<u32> = Vec::with_capacity(keywords.len() + 1);
    let mut flat: Vec<u16> = Vec::new();
    for pats in &keyword_patterns {
        offsets.push(flat.len() as u32);
        for &idx in pats {
            flat.push(idx as u16);
        }
    }
    offsets.push(flat.len() as u32);

    let mut code = String::new();
    code.push_str("// @generated by build.rs from src/patterns.tsv. Do not edit.\n\n");
    code.push_str(&format!(
        "pub const PATTERN_COUNT: usize = {};\n\n",
        patterns.len()
    ));

    code.push_str(&format!(
        "pub static PATTERN_SOURCES: [&str; {}] = [\n",
        patterns.len()
    ));
    for (provider, name, id, regex) in &patterns {
        code.push_str(&format!(
            "    // {} - {} [{}]\n",
            provider.replace('\n', " "),
            name.replace('\n', " "),
            id.replace('\n', " ")
        ));
        code.push_str(&format!("    {},\n", rust_raw(regex)));
    }
    code.push_str("];\n\n");

    code.push_str(&format!(
        "pub static PATTERN_IDS: [&str; {}] = [\n",
        patterns.len()
    ));
    for (_, _, id, _) in &patterns {
        code.push_str(&format!("    {},\n", rust_raw(id)));
    }
    code.push_str("];\n\n");

    code.push_str(&format!(
        "pub static PATTERN_PROVIDERS: [&str; {}] = [\n",
        patterns.len()
    ));
    for (provider, _, _, _) in &patterns {
        code.push_str(&format!("    {},\n", rust_raw(provider)));
    }
    code.push_str("];\n\n");

    code.push_str(&format!(
        "pub static PATTERN_NAMES: [&str; {}] = [\n",
        patterns.len()
    ));
    for (_, name, _, _) in &patterns {
        code.push_str(&format!("    {},\n", rust_raw(name)));
    }
    code.push_str("];\n\n");

    code.push_str(&format!(
        "pub static KEYWORDS: [&str; {}] = [\n",
        keywords.len()
    ));
    for keyword in &keywords {
        code.push_str(&format!("    {},\n", rust_raw(keyword)));
    }
    code.push_str("];\n\n");

    code.push_str(&format!(
        "pub static KEYWORD_OFFSETS: [u32; {}] = [\n",
        offsets.len()
    ));
    for offset in &offsets {
        code.push_str(&format!("    {offset},\n"));
    }
    code.push_str("];\n\n");

    code.push_str(&format!(
        "pub static KEYWORD_PATTERNS: [u16; {}] = [\n",
        flat.len()
    ));
    for idx in &flat {
        code.push_str(&format!("    {idx},\n"));
    }
    code.push_str("];\n\n");

    code.push_str(&format!(
        "pub static ALWAYS_EVALUATE: [u16; {}] = [\n",
        always.len()
    ));
    for idx in &always {
        code.push_str(&format!("    {idx},\n"));
    }
    code.push_str("];\n");

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("pattern_data.rs"), code).expect("write pattern_data.rs");
}

/// Remove `(?i)` / `(?i:...)` flags before parsing so case-insensitive
/// literals are represented as literals instead of one class per character.
fn strip_case_flags(pattern: &str) -> String {
    let bytes = pattern.as_bytes();
    let mut out = String::with_capacity(pattern.len());
    let mut i = 0;

    while i < bytes.len() {
        if bytes[i] == b'(' && i + 1 < bytes.len() && bytes[i + 1] == b'?' {
            if let Some(rel) = pattern[i + 2..].find(|c| c == ')' || c == ':') {
                let end = i + 2 + rel;
                let flags = &pattern[i + 2..end];
                let is_flag_group =
                    !flags.is_empty() && flags.chars().all(|c| c.is_ascii_alphabetic() || c == '-');
                if is_flag_group && flags.contains('i') {
                    if bytes[end] == b')' {
                        i = end + 1;
                        continue;
                    }
                    out.push_str("(?:");
                    i = end + 1;
                    continue;
                }
            }
        }

        out.push(bytes[i] as char);
        i += 1;
    }

    out
}

fn required_literals(pattern: &str, idx: usize) -> Vec<String> {
    let stripped = strip_case_flags(pattern);
    let hir = match Parser::new().parse(&stripped) {
        Ok(hir) => hir,
        Err(error) => {
            println!("cargo:warning=pattern {idx} could not be parsed for prefiltering: {error}");
            return Vec::new();
        }
    };

    let mut out = Vec::new();
    collect_required(&hir, &mut out);
    out.sort();
    out.dedup();
    out
}

/// Collect literals of which every match of `hir` contains at least one.
/// Returns true when at least one usable literal was found.
fn collect_required(hir: &Hir, out: &mut Vec<String>) -> bool {
    match hir.kind() {
        HirKind::Empty | HirKind::Look(_) | HirKind::Class(_) => false,
        HirKind::Literal(literal) => {
            if literal.0.len() < 3 {
                return false;
            }
            match std::str::from_utf8(&literal.0) {
                Ok(s) => {
                    out.push(s.to_ascii_lowercase());
                    true
                }
                Err(_) => false,
            }
        }
        HirKind::Repetition(rep) => {
            if rep.min == 0 {
                false
            } else {
                collect_required(&rep.sub, out)
            }
        }
        HirKind::Capture(capture) => collect_required(&capture.sub, out),
        HirKind::Concat(hirs) => {
            let mut found = false;
            for hir in hirs {
                found |= collect_required(hir, out);
            }
            found
        }
        HirKind::Alternation(hirs) => {
            let mut found = Vec::new();
            for hir in hirs {
                if !collect_required(hir, &mut found) {
                    // One branch can match without a usable literal, so this
                    // alternation cannot be filtered safely.
                    return false;
                }
            }
            out.extend(found);
            true
        }
    }
}

fn rust_raw(value: &str) -> String {
    let mut hashes = 1;
    loop {
        let closing = format!("\"{}", "#".repeat(hashes));
        if !value.contains(&closing) {
            break;
        }
        hashes += 1;
    }
    format!("r{0}\"{1}\"{0}", "#".repeat(hashes), value)
}
